function renderLocaleFile(locale, overrides) {
  const lines = [
    'import type { de } from "./de";',
    'import { en } from "./en";',
    "",
    `export const ${locale} = {`,
    "  ...en,"
  ];

  for (const [key, value] of Object.entries(overrides)) {
    const escaped = value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    lines.push(`  ${key}: "${escaped}",`);
  }

  lines.push("} satisfies Record<keyof typeof de, string>;");
  lines.push("");
  return lines.join("\n");
}

async function main() {
  for (const [locale, overrides] of Object.entries(phase1ByLocale)) {
    const filePath = path.join(localizationDir, `${locale}.ts`);
    const content = renderLocaleFile(locale, overrides);
    await fs.writeFile(filePath, content, "utf8");
    console.log(`Phase 1 translated: ${locale}.ts`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
