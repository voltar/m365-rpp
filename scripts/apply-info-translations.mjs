// Apply translations to each locale file
for (const [locale, overrides] of Object.entries(translations)) {
  const filePath = resolve(localesDir, `${locale}.ts`);
  let content = readFileSync(filePath, "utf-8");

  // Remove any existing overrides for these keys (in case they were already partially translated)
  for (const key of Object.keys(overrides)) {
    // Match lines like: "  keyName: "value","
    const regex = new RegExp(`^\\s*${key}:\\s*".*",?\\s*\\n`, "m");
    content = content.replace(regex, "");
  }

  // Find the closing `} satisfies` line
  const closingIndex = content.lastIndexOf("} satisfies Record<keyof typeof de, string>;");
  if (closingIndex === -1) {
    console.warn(`⚠️  ${locale}: Could not find closing brace pattern`);
    continue;
  }

  // Build the new override entries
  const entries = Object.entries(overrides)
    .map(([key, value]) => `  ${key}: "${value}",`)
    .join("\n");

  // Insert before the closing brace
  content = content.slice(0, closingIndex) + entries + "\n" + content.slice(closingIndex);
  writeFileSync(filePath, content, "utf-8");
  console.log(`✅ ${locale}: ${Object.keys(overrides).length} info keys added`);
}

